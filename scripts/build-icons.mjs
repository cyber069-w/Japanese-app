/**
 * Builds src/components/icons.generated.ts from the Tabler outline icons (MIT, https://tabler.io/icons).
 * Usage: node scripts/build-icons.mjs <path to @tabler/icons/icons/outline>
 * Only the icons listed in NAMES are bundled; keys are the names used with <Icon name="…"/>.
 */
import fs from 'node:fs';
import path from 'node:path';

const NAMES = {
  home: 'home', study: 'books', review: 'repeat', stats: 'chart-bar', settings: 'adjustments-horizontal',
  speaker: 'volume', bulb: 'bulb', x: 'x', check: 'check', right: 'arrow-right', left: 'arrow-left',
  chevron: 'chevron-right', flame: 'flame', target: 'target', clock: 'clock', calendar: 'calendar',
  upload: 'upload', download: 'download', trash: 'trash', mic: 'microphone', stop: 'player-stop',
  play: 'player-play', pen: 'pencil', undo: 'arrow-back-up', eye: 'eye', zap: 'bolt', grid: 'layout-grid',
  key: 'key', lock: 'lock', sparkle: 'sparkles', info: 'info-circle', sound: 'volume-off', refresh: 'refresh',
  phone: 'device-mobile', laptop: 'device-laptop', cloud: 'cloud', gauge: 'gauge', user: 'user', copy: 'copy',
  book: 'book',
  // courses
  language: 'language', 'chart-line': 'chart-line', bank: 'building-bank', scale: 'scale',
  // modules and exercises
  hiragana: 'language-hiragana', katakana: 'language-katakana', 'letter-a': 'letter-a', vocabulary: 'vocabulary',
  puzzle: 'puzzle', numbers: 'numbers', headphones: 'headphones', chat: 'message-circle', ear: 'ear',
  cards: 'cards', table: 'table', import: 'file-import', text: 'file-text', writing: 'writing',
  sort: 'arrows-sort', shapes: 'category', notebook: 'notebook', help: 'help-circle', exam: 'clipboard-check',
  math: 'math-function', keyboard: 'keyboard', list: 'list-check', diff: 'arrows-diff', kanji: 'writing-sign', bell: 'bell',
};

const dir = process.argv[2];
if (!dir) throw new Error('Pass the path to @tabler/icons/icons/outline');
const out = {};
for (const [key, file] of Object.entries(NAMES)) {
  const svg = fs.readFileSync(path.join(dir, `${file}.svg`), 'utf8');
  out[key] = [...svg.matchAll(/<path\s+d="([^"]+)"\s*\/>/g)].map((m) => m[1]).join(' ');
}
const body = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
fs.writeFileSync(
  new URL('../src/components/icons.generated.ts', import.meta.url),
  `// Generated by scripts/build-icons.mjs from Tabler Icons (MIT). Do not edit.\nexport const ICON_PATHS: Record<string, string> = {\n${body}\n};\n`,
);
console.log(`${Object.keys(out).length} icons`);
